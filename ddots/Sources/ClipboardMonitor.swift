import AppKit
import UniformTypeIdentifiers

enum ClipboardPasteboard {
    static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let legacySecrets: Set<NSPasteboard.PasteboardType> = [.init("com.agilebits.onepassword"), .init("net.antelle.keeweb")]
    static let legacyTransient = NSPasteboard.PasteboardType("de.petermaurer.TransientPasteboardType")
    static let generated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    static let source = NSPasteboard.PasteboardType("org.nspasteboard.source")
    static let video = NSPasteboard.PasteboardType("public.mpeg-4")
    static let supported: [NSPasteboard.PasteboardType] = [.fileURL, .png, .tiff, video, .init("com.apple.quicktime-movie"), .string]

    /// Must be called on the main thread. The permission gate runs before this content reader.
    static func read(_ board: NSPasteboard, source app: String, media: Bool) -> ClipboardInput? {
        let types = Set(board.types ?? [])
        let secret = types.contains(concealed) || !types.isDisjoint(with: legacySecrets)
        if types.contains(.fileURL), let urls = board.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            return ClipboardInput(kind: .files, files: urls.map(\.path), source: app, secret: secret)
        }
        if media {
            for type in [NSPasteboard.PasteboardType.png, .tiff, video, .init("com.apple.quicktime-movie")] where types.contains(type) {
                if let data = board.data(forType: type) {
                    return ClipboardInput(kind: type == .png || type == .tiff ? .image : .video, data: data, dataType: type.rawValue, source: app, secret: secret)
                }
            }
        }
        if let text = board.string(forType: .string), !text.isEmpty {
            return ClipboardInput(kind: .text, text: text, rtf: board.data(forType: .rtf), source: app, secret: secret)
        }
        return nil
    }
}

/// All pasteboard access and timer mutation are main-thread confined.
final class ClipboardMonitor {
    let board: NSPasteboard
    var onInput: ((ClipboardInput) -> Void)?
    var onPermission: ((Bool) -> Void)?
    var excludedApps: Set<String> = []
    var storesMedia = true
    var frontmostApp: () -> String = { NSWorkspace.shared.frontmostApplication?.bundleIdentifier ?? "" }
    var allowed: () -> Bool
    var canRequestPermission: () -> Bool
    var permissionReader: () -> Void
    func requestPermission() {
        precondition(Thread.isMainThread)
        guard running, !allowed(), canRequestPermission() else { return }
        // Suppress nested timer events while the system permission dialog runs its loop.
        performOwnWrite(permissionReader) // Discard the value; never send it to onInput.
        onPermission?(!allowed())
    }
    // Injection observes the exact content-read boundary, including forbidden-type tests.
    var reader: (NSPasteboard, String, Bool) -> ClipboardInput? = ClipboardPasteboard.read
    private var timer: Timer?
    private var lastCount: Int
    private var pendingCount: Int?
    private var emptyRetries = 0
    private var writingOwnContents = false
    private(set) var running = false
    var polling: Bool { timer?.isValid == true }
    init(board: NSPasteboard = .general, allowed: (() -> Bool)? = nil) {
        self.board = board; lastCount = board.changeCount
        canRequestPermission = {
            if #available(macOS 15.4, *) { return board.accessBehavior != .alwaysDeny }
            return false
        }
        permissionReader = { _ = board.string(forType: .string) }
        self.allowed = allowed ?? {
            if #available(macOS 15.4, *) { return board.accessBehavior == .alwaysAllow }
            return true
        }
    }
    func start() {
        precondition(Thread.isMainThread)
        guard !running else { return }
        lastCount = board.changeCount; pendingCount = nil; emptyRetries = 0
        running = true
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
        self.timer = timer; RunLoop.main.add(timer, forMode: .common)
        onPermission?(!allowed())
    }
    func stop() {
        precondition(Thread.isMainThread)
        running = false; timer?.invalidate(); timer = nil; pendingCount = nil
    }
    func ignoreOwnWrite() { lastCount = board.changeCount; pendingCount = nil }
    func performOwnWrite(_ action: () -> Void) {
        precondition(Thread.isMainThread)
        writingOwnContents = true
        defer { ignoreOwnWrite(); writingOwnContents = false }
        action()
    }
    func poll() {
        precondition(Thread.isMainThread)
        guard running, !writingOwnContents else { return }
        let count = board.changeCount
        let permission = allowed(); onPermission?(!permission)
        guard permission else { return }
        guard count != lastCount || pendingCount == count else { return }
        let types = Set(board.types ?? [])
        if types.isEmpty {
            if pendingCount != count { emptyRetries = 0 }
            emptyRetries += 1; pendingCount = emptyRetries <= 2 ? count : nil
            lastCount = count; return
        }
        lastCount = count; pendingCount = nil; emptyRetries = 0
        guard !types.contains(ClipboardPasteboard.transient), !types.contains(ClipboardPasteboard.generated), !types.contains(ClipboardPasteboard.legacyTransient) else { return }
        let app = board.string(forType: ClipboardPasteboard.source) ?? frontmostApp()
        guard !excludedApps.contains(app) else { return }
        let input = reader(board, app, storesMedia)
        guard board.changeCount == count, let input else { return }
        onInput?(input)
    }
    deinit { timer?.invalidate() }
}
