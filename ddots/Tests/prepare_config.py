"""Give legacy fake-Slack tests explicit metadata; never read the machine's Hermes home.

The routing corpus remains the generic fixture generated by the Hermes oracle.
Existing fake workspace identifiers are translated at the test boundary only.
"""
import json,sys
from pathlib import Path
root=Path(sys.argv[1]);root.mkdir(parents=True,exist_ok=True)
fixture=json.loads((Path(__file__).parent/'Fixtures/routing.json').read_text())
# These are the existing FakeSlack identities, not Slack account IDs.
profiles={'guide':'default','helper':'work-assistant','support':'sns-manager','doctor':'system-doctor','assistant':'personal-secretary'}
names={'default':'위키담당','work-assistant':'업무비서','sns-manager':'SNS담당','system-doctor':'진단담당','personal-secretary':'개인비서'}
def translate(value):
    if isinstance(value,dict):return {profiles.get(k,k):translate(v) for k,v in value.items()}
    if isinstance(value,list):return [translate(v) for v in value]
    if isinstance(value,str):return profiles.get(value,value)
    return value
value=translate(fixture)
for row in value['routing_samples']:
    for old,new in profiles.items():row['text']=row['text'].replace('@'+old, '@'+new)

for contract in value['routing'].values():
    for profile,name in names.items():contract['aliases'].setdefault(profile,[]).append(name)
    contract['aliases']['personal-secretary'] += ['개인비서','어둠의 개인비서']
    contract['aliases']['sns-manager'].append('SNS담당야')
value['members']=[{'profile':p,'displayName':n,'aliases':value['routing']['base']['aliases'].get(p,[])} for p,n in names.items()]
value['features']={'homeRoom':'workspace'}
value['rooms']={'SNS담당방':'sns-manager','업무비서방':'work-assistant','maintenance':'system-doctor','maintencance':'system-doctor','C_TEST_NOTICE':'system-doctor'}
(root/'ddots-config.json').write_text(json.dumps(value,ensure_ascii=False))
local={'schemaVersion':1,'homeLabel':'workspace','order':['default','personal-secretary','archive-helper','sns-manager','system-doctor','work-assistant'],
       'excluded':['research-assistant','archive-helper'],'roomLabels':{'secret':'새우튀김'},
       'threeTap':{'channel':'C_TEST_NOTICE','profile':'system-doctor'},'vaultBotUserID':'B_TEST_VAULT',
       'colors':{'default':'#112233','personal-secretary':'#223344','sns-manager':'#334455','system-doctor':'#445566'}}
(root/'ddots-local.json').write_text(json.dumps(local,ensure_ascii=False))
